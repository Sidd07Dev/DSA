""" Structure of Doubly Linked List Node
class Node:
    def __init__(self, val):
        self.data = val
        self.next = None
        self.prev = None
"""

class Solution:
    def reverse(self, head):
       curr=head
       while curr:
           prev=curr.prev
           next_p=curr.next
           curr.next=prev
           curr.prev=next_p
           head=curr
           curr=next_p
       return head
           
        
        

